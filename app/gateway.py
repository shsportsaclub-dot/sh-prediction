"""SH Cricket Data Gateway.

Our own data contract for fixtures, results, live scores, scorecards, commentary, squads, playing XI,
player / team / venue statistics and history. External data enters ONLY through a provider adapter
(manual entry, clearly labelled demo, or a future licensed feed), so a provider can be swapped without
touching the rest of the application. Building this gateway does not create live cricket data:
without a licensed feed, only verified manual entries and labelled demo data exist.
"""
import hashlib
import json
import threading
import time

from schema import now

# ------------------------------------------------------------------ read cache (short TTL)
_cache, _clock = {}, threading.Lock()
TTL = {"live": 5, "default": 30}

def cached(key, ttl, fn):
    with _clock:
        hit = _cache.get(key)
        if hit and time.time() - hit[0] < ttl:
            return hit[1]
    val = fn()
    with _clock:
        _cache[key] = (time.time(), val)
    return val

def clear_cache():
    with _clock:
        _cache.clear()

# ------------------------------------------------------------------ provider adapters
class ProviderAdapter:
    """fetch_fixtures() returns a list of normalized dicts:
    {provider_id, competition, season, home, away, start_utc, venue, city, format, match_no, source}"""
    name, kind = "base", "base"
    def fetch_fixtures(self):
        raise NotImplementedError

class DemoProvider(ProviderAdapter):
    """Clearly labelled demo fixtures with documented provenance (generated by SH, not real matches)."""
    name, kind = "demo", "demo"
    def fetch_fixtures(self):
        return [{"provider_id": "demo-%d" % i, "competition": "SH Demo League", "season": "Demo", "home": h, "away": a,
                 "start_utc": "2030-02-%02dT14:00:00+00:00" % (i + 1), "venue": "Demo Oval", "city": "", "format": "T10",
                 "match_no": "G%d" % (i + 1), "source": "SH demo generator (not a real match)"}
                for i, (h, a) in enumerate([("Demo Ultra Blasters", "Demo Coastal Kings"), ("Demo Eagle Eyes", "Demo Royal Rhinos")])]

class ManualProvider(ProviderAdapter):
    """Verified manual entry: rows are pushed by an admin (CSV import or forms), never fetched."""
    name, kind = "manual", "manual"
    def __init__(self, rows=None):
        self.rows = rows or []
    def fetch_fixtures(self):
        return self.rows

class LicensedFeedProvider(ProviderAdapter):
    """Placeholder for a licensed feed. Needs a contract + key set in the server environment.
    Deliberately does nothing until configured: we never scrape or use unauthorized data."""
    name, kind = "licensed_feed", "licensed"
    def __init__(self, config=None):
        self.config = config or {}
    def fetch_fixtures(self):
        raise RuntimeError("licensed feed not configured (no contract/key)")

ADAPTERS = {"demo": DemoProvider, "manual": ManualProvider, "licensed_feed": LicensedFeedProvider}

REQUIRED = ("provider_id", "competition", "home", "away", "start_utc", "source")

def validate(row):
    for k in REQUIRED:
        if not str(row.get(k) or "").strip():
            return "missing " + k
    if str(row["home"]).strip().casefold() == str(row["away"]).strip().casefold():
        return "teams must differ"
    # Require an actual timezone-aware timestamp; merely containing Z or + is not enough.
    import datetime
    try:
        dt = datetime.datetime.fromisoformat(str(row["start_utc"]).replace("Z", "+00:00"))
        if dt.tzinfo is None or dt.utcoffset() is None:
            return "start_utc needs a timezone"
    except (TypeError, ValueError, OverflowError):
        return "invalid start_utc timestamp"
    return None

def sync(c, provider_name, create_match, adapter=None, retries=3, backoff=0.2):
    """Pull fixtures through an adapter, validate, de-duplicate (data_provider_syncs + natural key), retry on failure."""
    p = c.execute("SELECT * FROM data_providers WHERE name=?", (provider_name,)).fetchone()
    if not p:
        raise LookupError("unknown provider")
    if not p["enabled"]:
        raise PermissionError("provider is disabled")
    if adapter is None:
        cls = ADAPTERS[provider_name]
        adapter = cls(json.loads(p["config_json"] or "{}")) if provider_name == "licensed_feed" else cls()
    c.execute("INSERT INTO data_sync_runs(provider,started_at,status) VALUES(?,?, 'running')", (provider_name, now()))
    run_id = c.execute("SELECT last_insert_rowid()").fetchone()[0]
    rows, err, attempt = None, None, 0
    for attempt in range(1, retries + 1):
        try:
            rows = adapter.fetch_fixtures()
            err = None
            break
        except Exception as e:  # network/provider failure: retry with backoff
            err = str(e)
            time.sleep(backoff * attempt)
    created = dup = rej = 0
    if rows is not None:
        for r in rows:
            problem = validate(r)
            if problem:
                rej += 1
                continue
            h = hashlib.sha256(json.dumps(r, sort_keys=True).encode()).hexdigest()
            res = create_match(dict(r, provider=provider_name, data_origin="demo" if adapter.kind == "demo" else "verified"))
            if res["status"] == "created":
                created += 1
            else:
                dup += 1
            c.execute("UPDATE data_provider_syncs SET payload_hash=?, synced_at=? WHERE provider=? AND provider_entity='match' AND provider_id=?",
                      (h, now(), provider_name, str(r["provider_id"])))
    status = "ok" if rows is not None else "failed"
    c.execute("UPDATE data_sync_runs SET finished_at=?,status=?,attempts=?,created=?,duplicates=?,rejected=?,error=? WHERE id=?",
              (now(), status, attempt, created, dup, rej, err, run_id))
    c.execute("UPDATE data_providers SET last_sync_at=?,last_status=?,last_error=? WHERE name=?", (now(), status, err, provider_name))
    clear_cache()
    return {"run_id": run_id, "status": status, "attempts": attempt, "created": created, "duplicates": dup, "rejected": rej, "error": err}
